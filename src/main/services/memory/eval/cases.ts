import type { EvolvesRelation, UnitType } from '@shared/memory/constants';

/** 用例维度；README 与报告按此分组 */
export const EVAL_DIMENSIONS = [
  'exact',
  'semantic',
  'crossLingual',
  'temporal',
  'entity',
  'typeFilter',
  'spaceIsolation',
  'distractor',
  'stale',
] as const;
export type EvalDimension = (typeof EVAL_DIMENSIONS)[number];

/** project = 当前项目；otherProject = 同库里另一个项目，用来验证隔离 */
export type EvalSpace = 'global' | 'project' | 'otherProject';

export interface EvalEntity {
  name: string;
  type: string;
  aliases?: string[];
}

export interface EvalMemory {
  /** 用例内引用名；运行器写库后映射到真实 id */
  key: string;
  content: string;
  space: EvalSpace;
  unitType: UnitType;
  importance?: number;
  eventStart?: string;
  eventEnd?: string;
  /** 写入时刻（ISO）；缺省按写入顺序递增，保证排序平局可复现 */
  createdAt?: string;
  /** 模拟异步 KG 抽取的结果，直接写实体层 */
  entities?: EvalEntity[];
  /** 写入时显式声明与本用例里更早一条记忆（key）的关系，走 createMemory 的 evolves 参数 */
  evolves?: { from: string; relation: EvolvesRelation };
}

export interface EvalCase {
  id: string;
  dimension: EvalDimension;
  description: string;
  memories: EvalMemory[];
  query: string;
  spaces: EvalSpace[];
  /** 模拟模型在工具参数里显式给出的事件时间窗 */
  eventDateFrom?: string;
  eventDateTo?: string;
  /** 只要某类型：searchMemories 没有类型参数，按 memoryAdmin 语义模式在结果上后过滤 */
  unitType?: UnitType;
  expected: string[];
  excluded: string[];
  /** 已过期 / 被新事实推翻的记忆：单独统计 staleRate，不计入噪声率 */
  stale?: string[];
}

